import {test} from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync,mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {profilesAPI as handler} from '../worker/profiles.ts';
const profilesAPI = (request, db) => handler(request, db, 'admin@example.test');
test('persistent lifecycle, authorization, invalid data, conflicts and revocation', async()=>{
 const dir=mkdtempSync(join(tmpdir(),'cuidar-')),file=join(dir,'db.sqlite'); let sqlite=new DatabaseSync(file);
 sqlite.exec(readFileSync(new URL('../drizzle/0000_wandering_bill_hollister.sql',import.meta.url),'utf8'));
 const db={prepare(sql){let args=[];return {bind(...a){args=a;return this},async first(){return sqlite.prepare(sql).get(...args)},async all(){return {results:sqlite.prepare(sql).all(...args)}},async run(){return {meta:sqlite.prepare(sql).run(...args)}}}}};
 const headers={'oai-authenticated-user-id':'test-owner','oai-authenticated-user-email':'admin@example.test','Origin':'https://example.test','Content-Type':'application/json'};
 const req=(path,method='GET',body,auth=true)=>new Request('https://example.test'+path,{method,headers:auth?headers:{Origin:'https://example.test','Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});
 const data={name:'Pessoa Teste',age:'30',allergies:'Fictícia',conditions:'',medicines:'',communication:'Fale devagar',contact:'Contato Teste',fictional:true};
 assert.equal((await profilesAPI(req('/api/profiles','POST',data,false),db)).status,403);
 assert.equal((await profilesAPI(req('/api/profiles','POST',{...data,fictional:false}),db)).status,400);
 let response=await profilesAPI(req('/api/profiles','POST',data),db);assert.equal(response.status,201);let p=await response.json();
 sqlite.close();sqlite=new DatabaseSync(file);
 let r=await profilesAPI(req('/api/public/profiles/'+p.slug,'GET',undefined,false),db);assert.equal(r.status,200);assert.equal((await r.json()).name,'Pessoa Teste');
 const change={...data,active:true,revision:p.revision,communication:'Use gestos'};
 r=await profilesAPI(req('/api/profiles/'+p.slug,'PUT',change),db);assert.equal(r.status,200);p=await r.json();
 assert.equal((await profilesAPI(req('/api/profiles/'+p.slug,'PUT',change),db)).status,409);
 assert.equal((await profilesAPI(req('/api/public/profiles/'+p.slug,'PUT',change,false),db)).status,405);
 const evil=req('/api/profiles','POST',data);evil.headers.set('Origin','https://evil.test');assert.equal((await profilesAPI(evil,db)).status,403);
 r=await profilesAPI(req('/api/profiles/'+p.slug,'PUT',{...change,revision:p.revision,active:false}),db);p=await r.json();
 assert.equal((await profilesAPI(req('/api/public/profiles/'+p.slug,'GET',undefined,false),db)).status,404);
 assert.equal((await profilesAPI(req('/api/profiles/'+p.slug,'DELETE',{revision:p.revision}),db)).status,200);
 assert.deepEqual(await (await profilesAPI(req('/api/profiles'),db)).json(),[]);
 sqlite.close();rmSync(dir,{recursive:true});
});
